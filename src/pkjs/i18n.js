// `s` in language `code`, {0}, {1}.. filled from the arguments after it.
function tr(code, s) {
  var args = arguments, out = (PAGE[code] || {})[s] || s;
  return out.replace(/\{(\d)\}/g, function (m, n) { return args[+n + 2]; });
}

